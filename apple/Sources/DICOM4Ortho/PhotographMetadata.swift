import Foundation
import DICOMCore

/// Patient, acquisition, and instance context supplied when materializing a photograph.
///
/// This value describes metadata, not capture-session state. DICOM Type 2 attributes
/// may be empty when unknown. Clinical mappings come from ``imageType``; they do not
/// infer patient identity, dates, or treatment history. Field formats and defaults
/// are documented below; validation of all DICOM VR limits is not yet implemented.
public struct PhotographMetadata: Sendable {
    /// Patient ID (LO). Empty when unknown; no identifier is inferred.
    public var patientID = ""
    /// Family-name component of DICOM Patient Name (PN).
    public var patientFamilyName = ""
    /// Given-name component of DICOM Patient Name (PN).
    public var patientGivenName = ""
    /// Birth date as a DICOM DA (`YYYYMMDD`), or empty when unknown.
    public var patientBirthDate = ""
    /// M/F/O or Male/Female/Other, case-insensitive; unrecognized values become empty.
    public var patientSex = ""
    /// Shared Study Instance UID. Set the same value on photographs from one study.
    public var studyInstanceUID: String
    /// Shared Series Instance UID, distinct from study and SOP instance UIDs.
    public var seriesInstanceUID: String
    /// Identity of the final instance. Reuse it only for the same materialized instance.
    public var sopInstanceUID: String
    /// ADA 1100 view keyword, for example `EV01` or `EV-01`.
    public var imageType: String
    /// Explicit terminology direction such as `projection_right`; required for IV28/IV30/EV40.
    public var directionKeyword: String?
    /// Photograph acquisition instant; editing/content timestamps are not substitutes.
    public var acquisitionDateTime: Date?
    /// Timezone for DICOM acquisition attributes and treatment-progress calendar-day arithmetic.
    /// Defaults to the process timezone; specify it for reproducible timezone behavior.
    public var acquisitionTimeZone: TimeZone = .current
    /// Optional treatment event/date pair from which the profile's day offset is calculated.
    public var treatmentProgress: TreatmentProgress?
    /// Responsible dental provider's family name, encoded as Physicians of Record.
    public var providerFamilyName = ""
    /// Responsible dental provider's given name, not the acquisition operator.
    public var providerGivenName = ""
    /// Acquisition operator's family name, encoded as Operators' Name.
    public var operatorFamilyName = ""
    /// Acquisition operator's given name, distinct from the responsible provider.
    public var operatorGivenName = ""

    /// Create metadata with independent final identity under dicom4ortho's registered UID roots.
    ///
    /// UID suffixes are generated by DICOMKit; no UID generation algorithm is reimplemented.
    /// For several photographs, replace study/series UIDs with their shared context while
    /// keeping a distinct SOP Instance UID for each image. Existing supplied UIDs are checked
    /// during materialization, not during this nonthrowing initializer.
    public init(imageType: String) {
        self.imageType = imageType
        studyInstanceUID = UIDGenerator(root: "1.3.6.1.4.1.61741.11.2.2").generate().value
        seriesInstanceUID = UIDGenerator(root: "1.3.6.1.4.1.61741.11.2.3").generate().value
        sopInstanceUID = UIDGenerator(root: "1.3.6.1.4.1.61741.11.2.4").generate().value
    }
}
